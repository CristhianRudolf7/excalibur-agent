#!/usr/bin/env python3
"""Generate the worldwide Windows zone map from CLDR 48 windowsZones.xml.

Download https://raw.githubusercontent.com/unicode-org/cldr/release-48/common/supplemental/windowsZones.xml
then pass the downloaded filename as the only argument. No network is used here.
"""

import json
from pathlib import Path
import subprocess
import sys
import xml.etree.ElementTree as ET


def main():
    root = ET.parse(sys.argv[1]).getroot()
    entries = {
        zone.attrib["other"]: zone.attrib["type"].split()[0]
        for zone in root.iter("mapZone")
        if zone.attrib["territory"] == "001"
    }
    target = Path(__file__).resolve().parent.parent / "internal/platform/windows_zones.go"
    header = """// Code generated by scripts/generate-windows-zones.py; DO NOT EDIT.
// Source: CLDR 48 common/supplemental/windowsZones.xml, territory 001.
// https://raw.githubusercontent.com/unicode-org/cldr/release-48/common/supplemental/windowsZones.xml
// Unicode data license: windows_zones.LICENSE.

package platform

// windowsZones maps Windows registry keys to CLDR's worldwide IANA defaults.
// A Windows key may cover several regions; territory 001 selects one default.
var windowsZones = map[string]string{
"""
    target.write_text(header + "".join(
        f"\t{json.dumps(key)}: {json.dumps(value)},\n"
        for key, value in sorted(entries.items())
    ) + "}\n", encoding="utf-8")
    subprocess.run(["gofmt", "-w", str(target)], check=True)


if __name__ == "__main__":
    main()
