#!/usr/bin/env python3
"""Generate only Robot Lab contract sections from packages/contracts/robotlab.json."""
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = json.loads((ROOT / 'packages/contracts/robotlab.json').read_text())
METHODS, DEFS, EVENTS = DOC['methods'], DOC['$defs'], DOC['events']


def pascal(name):
    return ''.join(part[:1].upper() + part[1:] for part in re.split(r'[._-]', name))


def ts(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(v) for v in schema['enum'])
    for union in ['oneOf', 'anyOf']:
        if union in schema:
            return ' | '.join(ts(v) for v in schema[union])
    kind = schema.get('type')
    if kind == 'array':
        return f'({ts(schema["items"])})[]'
    if kind == 'object':
        if not schema.get('properties'):
            return 'Record<string, never>' if schema.get('additionalProperties') is False else 'Record<string, unknown>'
        fields = '; '.join(json.dumps(k) + ('' if k in schema.get('required', []) else '?') + ': ' + ts(v) for k, v in schema['properties'].items())
        if schema.get('additionalProperties'):
            fields += '; [key: string]: unknown'
        return '{ ' + fields + ' }'
    return {'string': 'string', 'boolean': 'boolean', 'number': 'number', 'integer': 'number', 'null': 'null'}.get(kind, 'unknown')


def go(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'const' in schema:
        v = schema['const']
        return 'bool' if isinstance(v, bool) else 'int' if isinstance(v, int) else 'string'
    if 'anyOf' in schema or 'oneOf' in schema:
        return 'json.RawMessage'
    kind = schema.get('type')
    if kind == 'array':
        return '[]' + go(schema['items'])
    if kind == 'object':
        if not schema.get('properties'):
            return 'map[string]any'
        return 'struct {\n' + ''.join('\t' + pascal(k) + ' ' + go(v) + ' `json:"' + k + ('' if k in schema.get('required', []) else ',omitempty') + '"`\n' for k, v in schema['properties'].items()) + '}'
    return {'string': 'string', 'boolean': 'bool', 'number': 'float64', 'integer': 'int'}.get(kind, 'any')


def write(name, text):
    (ROOT / name).write_text(text)


def replace_lines(path, pattern, replacement):
    text = (ROOT / path).read_text()
    matches = list(re.finditer(pattern, text, re.M))
    if not matches:
        raise RuntimeError(f'No Robot Lab section in {path}')
    text = text[:matches[0].start()] + replacement + re.sub(pattern, '', text[matches[0].end():], flags=re.M)
    write(path, text)


# Export registries while preserving all unrelated entries byte for byte.
entries = []
for name, method in METHODS.items():
    def external(v):
        if isinstance(v, dict):
            return {k: ('robotlab.json' + item if k == '$ref' else external(item)) for k, item in v.items()}
        if isinstance(v, list):
            return [external(item) for item in v]
        return v
    entries.append('    ' + json.dumps(dict(name=name, family='robotlab', summary='Robot Lab ' + name[9:] + '.', params_schema=external(method['params']), result_schema=external(method['result']))) + ',\n')
replace_lines('packages/contracts/methods.json', r'^    \{"name": "robotlab\..*\n', ''.join(entries))
replace_lines('internal/api/methods.go', r'^\t\{"robotlab\..*\n', ''.join('\t{"' + name + '", "robotlab", "Robot Lab ' + name[9:] + '."},\n' for name in METHODS))
replace_lines('packages/contracts/events.json', r'^    \{"type": "robotlab\..*\n', ''.join('    ' + json.dumps(dict(type=name, payload='RobotLab' + pascal(name[9:]) + ('Event' if name not in ['robotlab.frame'] else ''), summary='Robot Lab ' + name[9:] + '.')) + ',\n' for name in EVENTS))
# Event aliases reference the exact same shapes as the v2 schema.
replace_lines('packages/contracts/events.json', r'^    "RobotLab[^\n]+\n', ''.join('    ' + json.dumps('RobotLab' + pascal(name[9:]) + ('Event' if name != 'robotlab.frame' else '')) + ': ' + json.dumps(external(schema)) + ',\n' for name, schema in EVENTS.items()))

api = '// Code generated by scripts/gen-robotlab-contracts.py; DO NOT EDIT.\npackage api\n\nimport "encoding/json"\n\n// CodeRobotLabUnavailable reports an unavailable runtime.\nconst CodeRobotLabUnavailable = -32020\n\n'
for name, schema in DEFS.items():
    shape = go(schema)
    api += 'type ' + name + (' = ' if shape == 'json.RawMessage' else ' ') + shape + '\n\n'
for name, method in METHODS.items():
    api += 'const MethodRobotLab' + pascal(name[9:]) + ' = ' + json.dumps(name) + '\n'
    api += 'type RobotLab' + pascal(name[9:]) + 'Params ' + go(method['params']) + '\n\n'
for name, schema in EVENTS.items():
    payload = 'RobotLab' + pascal(name[9:]) + ('Event' if name != 'robotlab.frame' else '')
    if payload not in DEFS:
        api += 'type ' + payload + ' ' + go(schema) + '\n\n'
api += 'func init() { EventTypes = append(EventTypes, []EventTypeInfo{\n'
for name in EVENTS:
    api += '{' + json.dumps(name) + ', ' + json.dumps('RobotLab' + pascal(name[9:]) + ('Event' if name != 'robotlab.frame' else '')) + ', ' + json.dumps('Robot Lab ' + name[9:] + '.') + '},\n'
api += '}...) }\n'
write('internal/api/robotlab.go', api)
write('internal/robotlab/schema_generated.go', '// Code generated by scripts/gen-robotlab-contracts.py; DO NOT EDIT.\npackage robotlab\n\nconst contractJSON = ' + json.dumps(json.dumps(DOC, separators=(',', ':'))) + '\n')
subprocess.run(['/usr/local/go/bin/gofmt', '-w', str(ROOT / 'internal/api/robotlab.go'), str(ROOT / 'internal/api/methods.go'), str(ROOT / 'internal/robotlab/schema_generated.go')], check=True)

web = (ROOT / 'apps/web/src/lib/rpc/contract.ts').read_text()
web = re.sub(r'\n// BEGIN GENERATED ROBOT LAB[\s\S]*?// END GENERATED ROBOT LAB\n?', '', web)
web = re.sub(r'^  // (?:BEGIN|END) GENERATED ROBOT LAB METHODS\n|^  \'robotlab\.[^\n]+\n', '', web, flags=re.M)
method_lines = '  // BEGIN GENERATED ROBOT LAB METHODS\n' + ''.join('  ' + repr(name) + ',\n' for name in METHODS) + '  // END GENERATED ROBOT LAB METHODS\n'
web = web.replace('export const clientMethods = [\n', 'export const clientMethods = [\n' + method_lines)
web += '\n// BEGIN GENERATED ROBOT LAB — run python3 scripts/gen-robotlab-contracts.py\n'
for name, schema in DEFS.items():
    web += 'export type ' + name + ' = ' + ts(schema) + '\n'
web += 'export interface RpcMethods {\n'
for name, method in METHODS.items():
    web += '  ' + repr(name) + ': { params: ' + ts(method['params']) + '; result: ' + ts(method['result']) + ' }\n'
web += '}\nexport interface RpcEvents {\n'
for name, schema in EVENTS.items():
    web += '  ' + repr(name) + ': ' + ts(schema) + '\n'
web += '}\n// END GENERATED ROBOT LAB\n'
write('apps/web/src/lib/rpc/contract.ts', web)
