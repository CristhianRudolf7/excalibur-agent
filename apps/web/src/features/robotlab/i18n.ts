export const robotlabMessages: Record<string, [string, string]> = Object.fromEntries(
  Object.entries(messages).map(([key, [en, es]]) => [`lab_${key}`, [es, en]]),
)
export type LabMessage = keyof typeof messages
export function useLabText() {
  const { t, i18n } = useTranslation()
  const language: 'es' | 'en' = i18n.language.startsWith('es') ? 'es' : 'en'
  return {
    language,
    text: (key: LabMessage) => t(`lab_${key}`),
    statusText: (status: string) =>
      t(`lab_${status === 'pending' ? 'pendingStatus' : status}`, { defaultValue: status }),
  }
}
