func TestSourceReadabilityThresholds(t *testing.T) {
	for _, tc := range []struct {
		name, path, source, diagnostic string
	}{
		{"line boundary", "app.js", strings.Repeat("a", 200) + "\nx\nx\n", ""},
		{"long line", "app.js", "// heading\n" + strings.Repeat("a", 201), "app.js:2: code line"},
		{"average boundary", "app.js", strings.Repeat("a", 100), ""},
		{"average over", "app.js", strings.Repeat("a", 101), "average code line length"},
		{"two statements", "app.js", "const first = 1; const second = 2;", ""},
		{"three statements", "app.js", "const first=1;const second=2;const third=3;", "app.js:1: 3 top-level"},
		{"loop separators", "app.js", "for (let index=0;index<5;index++) { visit(index); }", ""},
		{"block closure", "app.js", "function render() {\n}\nconst first=1;const second=2;const third=3;", "app.js:3: 3 top-level"},
		{"strings and comments", "app.js", "const text = '" + strings.Repeat("long", 200) + "'; // " + strings.Repeat("comment", 100), ""},
		{"escaped quotes", "app.js", `const text = 'escaped\'` + strings.Repeat("long", 200) + `';`, ""},
		{"triple quoted", "app.py", "text = \"\"\"" + strings.Repeat("long", 200) + "\n# still a string\"\"\"\n", ""},
		{"raw literal", "app.go", "var text = `" + strings.Repeat("long", 200) + "`\n", ""},
		{"data table", "data.js", "const rows = [" + strings.Repeat("[123,456],", 100) + "];", ""},
		{"template code", "app.js", "const text = `value ${" + strings.Repeat("value + ", 30) + "value}`;", "app.js:1: code line"},
		{"module boundary", "app.js", strings.Repeat("run();\n", 600), ""},
		{"large module", "app.js", strings.Repeat("run();\n", 601), "app.js:601: source has 601"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			pending := strings.Join(sourceReadability(tc.path, tc.source), "\n")
			if tc.diagnostic == "" && pending != "" || tc.diagnostic != "" && !strings.Contains(pending, tc.diagnostic) {
				t.Fatalf("diagnostics %q, expected %q", pending, tc.diagnostic)
			}
		})
	}
}

func TestDeliverySourceScanExclusionsAndUnlistedFiles(t *testing.T) {
	e, manifest := evidenceFixture(t)
	compressed := strings.Repeat("doSomething();", 30)
	for _, path := range []string{"dist/app.js", "build/app.js", "node_modules/library/index.js", "vendor/lib.go", "generated/client.ts", ".venv/module.py", "package-lock.json", "data.json", "generated.go", "components/hidden.tsx"} {
		full := filepath.Join(e.dir, path)
		if err := os.MkdirAll(filepath.Dir(full), 0700); err != nil {
			t.Fatal(err)
		}
		content := compressed
		if path == "generated.go" {
			content = "// Code generated by fixture. DO NOT EDIT.\n" + content
		}
		if err := os.WriteFile(full, []byte(content), 0600); err != nil {
			t.Fatal(err)
		}
	}
	writeEvidence(t, e, manifest)
	report := e.check()
	diagnostic := strings.Join(report.Pendings, "\n")
	if report.OK || !strings.Contains(diagnostic, "components/hidden.tsx:1:") {
		t.Fatal(report)
	}
	for _, excluded := range []string{"dist/app", "build/app", "node_modules/", "vendor/", "generated/", ".venv/", "lock.json", "data.json", "generated.go"} {
		if strings.Contains(diagnostic, excluded) {
			t.Fatal("excluded file scanned", diagnostic)
		}
	}
}

func TestDeliveryFormatterRequiresActualFreshSuccessfulCoverage(t *testing.T) {
	e, manifest := evidenceFixture(t)
	root, err := os.OpenRoot(e.dir)
	if err != nil {
		t.Fatal(err)
	}
	defer root.Close()
	for _, tc := range []struct {
		command string
		valid   bool
	}{
		{"prettier --check .", true}, {"./node_modules/.bin/prettier --write .", true},
		{"npx --no-install prettier --check app.js", true}, {"gofmt -w .", true},
		{"python3 -m black --check .", true}, {"black .", true},
		{"echo prettier --check .", false}, {"npx prettier --check .", false},
		{"gofmt -l .", false}, {"black --diff .", false},
		{"prettier --version --check .", false}, {"prettier --check . || true", false},
	} {
		if got := formatterCommand(root, tc.command); got != tc.valid {
			t.Errorf("formatter %q: got %v", tc.command, got)
		}
	}
	if err := os.WriteFile(filepath.Join(e.dir, "package.json"), []byte(`{"scripts":{"format:check":"prettier --check .","fake":"echo prettier --check ."}}`), 0600); err != nil {
		t.Fatal(err)
	}
	if !formatterCommand(root, "npm run format:check") || formatterCommand(root, "npm run fake") {
		t.Fatal("project script validation")
	}
	for _, command := range []string{"gofmt -w .", "prettier --check other.js", "prettier --check --config ."} {
		if formatterCovers(root, command, "app.js") {
			t.Fatal("unrelated formatter covers source", command)
		}
	}
	if !formatterCovers(root, "npm run format:check", "app.js") {
		t.Fatal("project formatter did not cover source")
	}
	manifest["formatters"] = []deliveryFormatter{{Check: "prettier --check .", Files: []string{"app.js"}}}
	writeEvidence(t, e, manifest)
	failure := 1
	e.observe("exec", json.RawMessage(`{"command":"prettier --check ."}`), tools.Result{Status: tools.StatusToolError, ExitCode: &failure})
	if !strings.Contains(strings.Join(e.check().Pendings, "\n"), "app.js:1: run the formatter") {
		t.Fatal("failed formatter accepted")
	}
	success := 0
	e.observe("exec", json.RawMessage(`{"command":"prettier --check ."}`), tools.Result{Status: tools.StatusOK, ExitCode: &success})
	future := time.Now().Add(time.Minute)
	if err := os.Chtimes(filepath.Join(e.dir, "app.js"), future, future); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(strings.Join(e.check().Pendings, "\n"), "app.js:1: run the formatter") {
		t.Fatal("stale formatter accepted")
	}
}
