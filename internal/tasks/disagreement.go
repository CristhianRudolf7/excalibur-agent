package tasks

import "strings"

// DisagreementProtocolEnabled controls sample reconciliation before rewrites.
func DisagreementProtocolEnabled() bool { return envBool("EXCALIBUR_DISAGREEMENT_PROTOCOL", true) }

// DisagreementReviewGuidance is shared by the full and recovery review prompts.
// Literal-rule reconciliation is useful for interactive assistants as well.
func DisagreementReviewGuidance() string {
	if !DisagreementProtocolEnabled() {
		return ""
	}
	return "- On oracle disagreement, request concrete samples showing which result follows the literal request before changing the deliverable; never blindly adopt oracle output. For a direct rule already checked on inspected samples, reconcile samples instead of demanding a fresh independent oracle; FRESH_INPUTS may be NA with those samples cited.\n"
}

func generalizationInstructions() string {
	if !DisagreementProtocolEnabled() {
		return generalizeInstructions
	}
	text := strings.Replace(generalizeInstructions,
		"require at least one executed check on fresh inputs generated by the agent:",
		"unless a direct rule was already checked on inspected samples, require at least one executed check on fresh inputs generated by the agent:", 1)
	return strings.Replace(text, "whenever fresh-input evidence or any explicit property check is absent", "whenever applicable fresh-input evidence (or inspected direct-rule samples) or any explicit property check is absent", 1)
}
